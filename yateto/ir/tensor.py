from .core import Op


def mayFuseGroups(indices, groups, layout):
  """Whether the axes of each group lie together in the layout.

  A matrix product has two dimensions per operand, and an operand with more
  axes than that is read as if the axes of each group were one axis. They are
  one only where they lie consecutively in storage, so this is what decides
  whether the operand can be read as a matrix at all -- asked of what the
  statement states, the index tuple and the groups it contracts over, and of
  the layout the operand would be read with.
  """
  return all(layout.mayFuse(indices.positions(group)) for group in groups)


class TensorOp(Op):
  """One statement, still stated over whole tensors.

  This is the level the control-flow graph works at and the level the export
  description speaks: a destination, a few operands with their index maps, a
  scale factor, and whether the value is accumulated. It says what is to be
  computed and not how, so it is also the level an external generator can take
  a statement away at -- a `lower()` that never runs is a statement someone
  else is generating.

  `result` and `terms` are tensor descriptions as the code generators hand
  them over: a name, an index tuple, a memory layout, an equivalent sparsity
  pattern and a datatype. An operand may also be an immediate the operation
  was written with, in which case it is a number.
  """

  def __init__(self, result, terms, alpha=1.0, add=False, loopRanges=None,
               unrolled=False, generator=None):
    self.result = result
    self.terms = list(terms)
    #: What the value is scaled by: a number, or the name of a scalar the
    #: kernel is given.
    self.alpha = alpha
    #: Accumulate into the destination rather than overwrite it.
    self.add = add
    #: index name -> Range, the space the statement runs over.
    self.loopRanges = dict(loopRanges) if loopRanges else {}
    #: Run over the entries rather than over the ranges. A sparse layout has
    #: an address for an entry and none for an index, so a statement that
    #: touches one has to name the entries it visits.
    self.unrolled = unrolled
    #: The backend that has claimed this statement. Which one that is falls
    #: out of what the statement is and what it is generated for; what it
    #: writes -- loops put here in the statement's place, or the statement
    #: itself, straight into the kernel -- is settled when the statement is
    #: lowered, which happens to the region and not while it is built.
    self.generator = generator

  def lower(self):
    """The statement as loops and scalar operations."""
    raise NotImplementedError(
      f'{type(self).__name__} is still generated by its own backend and has no '
      f'lowering yet.')

  def touched(self):
    """The tensors the statement reaches, and the ones it writes.

    An operand that is a number the operation was written with is not one of
    them: it has no storage to reach.
    """
    reached = [term for term in [self.result] + self.terms
               if hasattr(term, 'memoryLayout')]
    return reached, [self.result]

  def __repr__(self):
    return f'{type(self).__name__}({self.result.name})'


class Copy(TensorOp):
  """``result <op>= alpha * term`` over the same indices."""

  def lower(self):
    from .lower import lowerScaleAdd
    return lowerScaleAdd(self)


class Transpose(Copy):
  """The same, with the operand's axes in another order."""


class Broadcast(Copy):
  """The same, with the operand lacking indices the destination has.

  A missing index is not addressed on the operand, so the same entry is read
  for every value of it.
  """


class Elementwise(TensorOp):
  """An operation applied entry by entry over one index space."""

  def __init__(self, result, terms, optype, alpha=1.0, add=False,
               loopRanges=None, unrolled=False, generator=None):
    super().__init__(result, terms, alpha, add, loopRanges, unrolled, generator)
    self.optype = optype

  def lower(self):
    from .lower import lowerElementwise
    return lowerElementwise(self)


class LoopOverGEMM(TensorOp):
  """A contraction of two operands, run as a loop over matrix products."""

  def __init__(self, result, terms, transA=False, transB=False, alpha=1.0,
               add=False, loopRanges=None, generator=None, prefetch=None,
               m=None, n=None, k=None):
    super().__init__(result, terms, alpha, add, loopRanges, generator=generator)
    #: The index groups the product is formed over: `m` and `n` are the free
    #: indices of the left and of the right operand, `k` the ones summed
    #: away. Two per operand, which is what makes a product a matrix product.
    self.m = m
    self.n = n
    self.k = k
    #: The tensor to fetch while the products run, where one was assigned. It
    #: is nothing the statement computes with, and everything the kernel is
    #: handed is in the statement that names it.
    self.prefetch = prefetch
    #: Whether an operand is read with its two axes the other way round. Which
    #: axis goes where is in the index maps as well; the flags say it in the
    #: terms a matrix product is stated in.
    self.transA = transA
    self.transB = transB

  def mayReadOperands(self, layouts=None):
    """Whether the operands can be read as matrices, laid out like this.

    The layouts default to the ones the operands state; another set is asked
    about where a pass is considering reading an operand from somewhere else.
    """
    if layouts is None:
      layouts = [term.memoryLayout for term in self.terms]
    return mayFuseGroups(self.terms[0].indices, (self.m, self.k), layouts[0]) \
       and mayFuseGroups(self.terms[1].indices, (self.k, self.n), layouts[1])

  def mayWriteResult(self, layout=None):
    """Whether the product can be written into a destination laid out like this."""
    layout = self.result.memoryLayout if layout is None else layout
    return mayFuseGroups(self.result.indices, (self.m, self.n), layout)

  def isPureGEMM(self):
    """Whether the statement is a matrix product and nothing around it.

    Two operands of two axes each sharing exactly one of them: then there is
    no loop over the product and no axis left over to address before it
    starts, which is what a backend taking whole chains of them expects.
    """
    left, right = (term.indices for term in self.terms)
    return len(left) == 2 and len(right) == 2 and len(left - right) == 1


class FusedGEMMs(TensorOp):
  """Contractions one backend takes together.

  Each of them is a statement in its own right and stands here as one. What
  the chain writes is what the last of them writes; what it reaches, and what
  it leaves behind on the way, is what they reach and leave behind between
  them.
  """

  def __init__(self, statements, generator=None):
    last = statements[-1]
    super().__init__(last.result,
                     [term for statement in statements for term in statement.terms],
                     alpha=last.alpha, add=last.add, generator=generator)
    self.statements = list(statements)

  def touched(self):
    reached, written = [], []
    for statement in self.statements:
      inner, outer = statement.touched()
      reached.extend(inner)
      written.extend(outer)
    return reached, written


class Reduction(TensorOp):
  """An operation folding one index of its operand away."""

  def __init__(self, result, terms, optype, sumIndex, sumRange, alpha=1.0,
               add=False, loopRanges=None, generator=None):
    super().__init__(result, terms, alpha, add, loopRanges, generator=generator)
    self.optype = optype
    #: The index that is folded away, which the destination does not have.
    self.sumIndex = str(sumIndex)
    #: The range that index runs over.
    self.sumRange = sumRange

  def lower(self):
    from .lower import lowerReduction
    return lowerReduction(self)
